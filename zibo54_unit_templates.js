function stripLockTagText(str) {
  return String(str || '')
    .replace(/【?🔒待精校[^】]*】?/g, '')
    .replace(/🔒待精校/g, '')
    .trim();
}

function buildDynamicUnitTemplatesFromKps(curSubjName, curSem, chapName, kps) {
  if (Array.isArray(chapName) && !kps) {
    kps = chapName;
    chapName = curSem;
    curSem = (kps[0] && kps[0].semester) || '初一上';
  }
  const safeKps = Array.isArray(kps) ? kps : [];
  const cards = safeKps.map((kp, idx) => {
    const title = stripLockTagText(kp.corePoint || kp.title || `第 ${idx + 1} 课核心母题`);
    const qMainClean = stripLockTagText(cleanTextForDisplay(kp.questionMain, 110));
    const lookLike = qMainClean
      ? `当同步练习出现类似：「${qMainClean}」或考查【${title}】核心概念与变式时。`
      : `当题干考查【${title}】的定义辨析、标准计算或材料应用时。`;

    let howToWrite = [];
    if (kp.sections && kp.sections.refSkills) {
      howToWrite = kp.sections.refSkills
        .split('\n')
        .map(l => stripLockTagText(cleanTextForDisplay(l, 140)))
        .filter(l => l.length > 6)
        .slice(0, 3);
    }
    if (howToWrite.length < 2) {
      const m = stripLockTagText(cleanTextForDisplay(kp.mnemonic, 120)) || '先圈题干限定词，调取本课核心法则';
      const u = stripLockTagText(cleanTextForDisplay(kp.understanding, 140)) || '按教材标准步骤逐行推导，严禁跳步';
      const w = stripLockTagText(cleanTextForDisplay(kp.habitWarning || kp.errorReason, 130)) || '代入结果逆向检验符号与单位';
      howToWrite = [
        `第 1 步【认题眼调口诀】：${m}`,
        `第 2 步【按固定逻辑落笔】：${u}`,
        `第 3 步【防坑复核检验】：${w}`
      ];
    }

    const q0 = (kp.quizItems && kp.quizItems[0]) ? kp.quizItems[0] : null;
    const sampleQ = stripLockTagText(cleanTextForDisplay(kp.questionMain, 180)) || (q0 ? (q0.prompt || q0.q) : `【同步练习母题】围绕「${title}」的标准应用题`);
    const sampleA = stripLockTagText(cleanTextForDisplay(kp.answerText, 240)) || (q0 && typeof formatQuizItemSampleAnswer === 'function' ? formatQuizItemSampleAnswer(q0) : '按上方 1-2-3 步标准格式分步作答。');
    const sampleLines = sampleA.split(/[；;\n]+/).map(s => s.trim()).filter(Boolean).slice(0, 4);

    return {
      kpId: kp.id,
      badge: `本单元母题 ${idx + 1}`,
      title,
      lookLike,
      howToWrite,
      sample: {
        question: sampleQ,
        lines: sampleLines.length > 0 ? sampleLines : [sampleA],
        trap: stripLockTagText(cleanTextForDisplay(kp.habitWarning || kp.errorReason || kp.mnemonic, 150)) || '严格按步骤分行书写，切忌跳步漏项。'
      }
    };
  });

  return {
    unitTag: `淄博五四制 · ${curSubjName}（${curSem || '同步'}） · ${chapName}`,
    unitGoal: `紧扣 ${curSem || ''}《${chapName}》共 ${safeKps.length} 课核心考点，按「长什么样 ➔ 怎么下笔 ➔ 标准书写样板」三步规范作答。`,
    templates: cards
  };
}

function getZibo54UnitTemplateData(curSubjName, semOrChap, chapOrKps, maybeKps) {
  let curSem = '初一上';
  let chapName = semOrChap;
  let kps = chapOrKps;
  if (Array.isArray(maybeKps) || typeof chapOrKps === 'string') {
    curSem = semOrChap || '初一上';
    chapName = chapOrKps || '';
    kps = Array.isArray(maybeKps) ? maybeKps : [];
  } else if (Array.isArray(kps) && kps[0] && kps[0].semester) {
    curSem = kps[0].semester;
  }
  if (curSem === '初一上') {
    const subjMap = window.ZIBO54_UNIT_TEMPLATE_DB[curSubjName] || {};
    if (subjMap[chapName]) {
      return subjMap[chapName];
    }
    // 模糊匹配章节名（仅限初一上）
    const normTarget = String(chapName || '').replace(/\s+/g, '');
    for (const key of Object.keys(subjMap)) {
      if (key.replace(/\s+/g, '') === normTarget || normTarget.includes(key.replace(/\s+/g, '')) || key.replace(/\s+/g, '').includes(normTarget)) {
        return subjMap[key];
      }
    }
  }
  return buildDynamicUnitTemplatesFromKps(curSubjName, curSem, chapName, kps || []);
}
window.getZibo54UnitTemplateData = getZibo54UnitTemplateData;

